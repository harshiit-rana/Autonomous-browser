/**
 * Project Aegis - Markdown Report Synthesizer with Chart & Graph Generation
 * 
 * Implements:
 * - Issue #80: DATA-04 Markdown Report Synthesizer with Chart & Graph Generation
 */

export interface ReportSection {
  title: string;
  content: string;
  tableData?: { headers: string[]; rows: string[][] };
  chartMermaid?: string;
}

export interface ReportConfig {
  title: string;
  goal: string;
  author?: string;
  sections: ReportSection[];
  sources: Array<{ title: string; url: string }>;
}

export class ReportSynthesizer {
  /**
   * Generates a comprehensive GitHub Flavored Markdown report.
   */
  public static generateMarkdown(config: ReportConfig): string {
    const lines: string[] = [];

    // Header
    lines.push(`# ${config.title}`);
    lines.push(`> **Goal:** ${config.goal}`);
    lines.push(`> **Generated By:** Project Aegis Autonomous Agent (${config.author || 'Aegis Swarm'})`);
    lines.push(`> **Timestamp:** ${new Date().toISOString()}`);
    lines.push('');
    lines.push('---');
    lines.push('');

    // Table of Contents
    lines.push('## 📑 Table of Contents');
    config.sections.forEach((sec, idx) => {
      const anchor = sec.title.toLowerCase().replace(/[^a-z0-9]+/g, '-');
      lines.push(`${idx + 1}. [${sec.title}](#${anchor})`);
    });
    lines.push(`${config.sections.length + 1}. [Sources & Citations](#sources--citations)`);
    lines.push('');
    lines.push('---');
    lines.push('');

    // Sections
    for (const sec of config.sections) {
      lines.push(`## ${sec.title}`);
      lines.push(sec.content);
      lines.push('');

      // Render Markdown Table
      if (sec.tableData && sec.tableData.headers.length > 0) {
        const { headers, rows } = sec.tableData;
        lines.push('| ' + headers.join(' | ') + ' |');
        lines.push('| ' + headers.map(() => '---').join(' | ') + ' |');
        for (const r of rows) {
          lines.push('| ' + r.map(c => c.replace(/\|/g, '\\|')).join(' | ') + ' |');
        }
        lines.push('');
      }

      // Render Mermaid Chart
      if (sec.chartMermaid) {
        lines.push('```mermaid');
        lines.push(sec.chartMermaid);
        lines.push('```');
        lines.push('');
      }

      lines.push('---');
      lines.push('');
    }

    // Sources & Citations
    lines.push('## 🔗 Sources & Citations');
    if (config.sources.length === 0) {
      lines.push('_No external sources referenced._');
    } else {
      lines.push('| # | Page Title | URL |');
      lines.push('|---|---|---|');
      config.sources.forEach((src, idx) => {
        lines.push(`| ${idx + 1} | ${src.title} | [${src.url}](${src.url}) |`);
      });
    }

    return lines.join('\n');
  }

  /**
   * Helper to format a Mermaid Pie Chart.
   */
  public static makeMermaidPie(title: string, data: Record<string, number>): string {
    const lines = [`pie title ${title}`];
    for (const [label, val] of Object.entries(data)) {
      lines.push(`  "${label}" : ${val}`);
    }
    return lines.join('\n');
  }
}
