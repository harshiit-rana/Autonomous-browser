#!/usr/bin/env node

/**
 * Status Document Generator (Issue #220 - [TRU-02])
 *
 * Reads docs/reachability_audit.json and scripts/reachability_allowlist.json
 * Generates docs/STATUS.md with a cryptographic hash of reachability_audit.json in line 1.
 */

import * as crypto from 'node:crypto';
import * as fs from 'node:fs';
import * as path from 'node:path';
import { fileURLToPath } from 'node:url';
import { buildIssueVerification } from './build_issue_verification.mjs';

const __filename = fileURLToPath(import.meta.url);
const __dirname = path.dirname(__filename);
const ROOT_DIR = path.resolve(__dirname, '..');

export function generateStatusDoc() {
  const auditPath = path.join(ROOT_DIR, 'docs', 'reachability_audit.json');
  const allowlistPath = path.join(ROOT_DIR, 'scripts', 'reachability_allowlist.json');
  const statusPath = path.join(ROOT_DIR, 'docs', 'STATUS.md');

  // Ensure issue verification ledger is up to date
  let issueVer = null;
  try {
    issueVer = buildIssueVerification();
  } catch (err) {
    const issueVerPath = path.join(ROOT_DIR, 'docs', 'audits', 'issue_verification.json');
    if (fs.existsSync(issueVerPath)) {
      issueVer = JSON.parse(fs.readFileSync(issueVerPath, 'utf8'));
    }
  }

  if (!fs.existsSync(auditPath)) {
    throw new Error('docs/reachability_audit.json not found. Run node scripts/audit_reachability.mjs first.');
  }

  const auditRaw = fs.readFileSync(auditPath, 'utf8');
  const modules = JSON.parse(auditRaw).sort((a, b) => a.path.localeCompare(b.path));
  const canonical = JSON.stringify(modules, null, 2);
  const sha256 = crypto.createHash('sha256').update(canonical).digest('hex');

  let allowlist = { testOnly: [], attic: [], pending: {} };
  if (fs.existsSync(allowlistPath)) {
    allowlist = JSON.parse(fs.readFileSync(allowlistPath, 'utf8'));
  }

  const testOnlySet = new Set(allowlist.testOnly || []);
  const atticSet = new Set(allowlist.attic || []);
  const pendingMap = allowlist.pending || {};

  const reachableCount = modules.filter((m) => m.isReachable).length;
  const orphanedCount = modules.filter((m) => !m.isReachable).length;

  const lines = [
    `<!-- generated by scripts/gen_status.mjs from ${sha256}; do not edit -->`,
    '# Project Aegis - Component Status & Reachability Ledger',
    '',
    `> **Audited Modules:** ${modules.length} total in \`src/\`  `,
    `> **Reachable from Application Entry Points:** ${reachableCount} (${Math.round((reachableCount / modules.length) * 100)}%)  `,
    `> **Orphaned (Pending Integration / Test-only):** ${orphanedCount} (${Math.round((orphanedCount / modules.length) * 100)}%)  `,
    `> **Governing Completion Roadmap:** [Issue #218 - Completion Program Index](https://github.com/harshiit-rana/Autonomous-browser/issues/218)`,
    '',
    '---',
    '',
    '## 1. Executive Summary',
    '',
    'This ledger is generated programmatically from `docs/reachability_audit.json` and `scripts/reachability_allowlist.json`.',
    'No numbers or reachable statuses in this document are edited by hand.',
    '',
    '### Reachability Rules & Categories',
    '- **Reachable (Yes):** Imported and reachable via production runtime entry points (`src/main/index.ts`, `src/main/preload.ts`, or `src/renderer/app.ts`).',
    '- **Test-Only:** Modules designed exclusively for synthetic evaluation, benchmarking, or security red-teaming (e.g. `src/testing/`, `src/evaluation/`).',
    '- **Pending:** Orphaned production modules currently assigned to specific completion program issues (#223 - #262).',
    '- **Attic:** Deprecated or quarantined modules moved out of active development paths.',
    '',
    '---',
    '',
    '## 2. Module Inventory & Disposition Matrix',
    '',
    '| Subsystem / Area | Module File | Reachable | Disposition | Owning Issue / Program Track |',
    '|:---|:---|:---:|:---:|:---:|'
  ];

  // Sort modules by subsystem then path
  const sorted = [...modules].sort((a, b) => a.path.localeCompare(b.path));

  for (const m of sorted) {
    const parts = m.path.split('/');
    const area = parts.length > 1 ? parts[0] : 'root';
    const filePath = `src/${m.path}`;

    let reachableLabel = 'No';
    let disposition = 'Pending Integration';
    let owningIssue = pendingMap[m.path] || '#221';

    if (m.isReachable) {
      reachableLabel = 'Yes';
      disposition = 'Wired in Production';
      owningIssue = 'Core Runtime';
    } else if (testOnlySet.has(m.path)) {
      reachableLabel = 'Test-Only';
      disposition = 'Test Infrastructure';
      owningIssue = 'Testing Suite';
    } else if (atticSet.has(m.path)) {
      reachableLabel = 'Attic';
      disposition = 'Quarantined';
      owningIssue = '#192 / ADR-006';
    }

    lines.push(`| **${area}** | \`${filePath}\` | ${reachableLabel} | ${disposition} | ${owningIssue} |`);
  }

  if (issueVer) {
    lines.push('');
    lines.push('---');
    lines.push('');
    lines.push('## 3. Legacy Issue Verification Summary (#101 - #217)');
    lines.push('');
    lines.push('An exhaustive audit of all 117 closed historical issues (#101–#217) was conducted under [Issue #222](https://github.com/harshiit-rana/Autonomous-browser/issues/222). Detailed findings per issue are recorded in [`docs/audits/ISSUE_VERIFICATION.md`](audits/ISSUE_VERIFICATION.md).');
    lines.push('');
    lines.push('| Category | Count | Percentage | Definition & Verification Gate |');
    lines.push('|:---|:---:|:---:|:---|');
    lines.push(`| **Fully Verified** | ${issueVer.verified} | ${Math.round((issueVer.verified / issueVer.total) * 100)}% | Requires live Playwright \`_electron\` E2E test (#254) or manual run log/screenshot (#223). |`);
    lines.push(`| **Partial** | ${issueVer.partial} | ${Math.round((issueVer.partial / issueVer.total) * 100)}% | Code and unit tests exist; live running-app e2e verification pending in completion program. |`);
    lines.push(`| **Not in App** | ${issueVer.notInApp} | ${Math.round((issueVer.notInApp / issueVer.total) * 100)}% | Orphaned, quarantined in \`attic/\`, mock-only, or pure specification/doc not in runtime. |`);
    lines.push(`| **Total Audited** | **${issueVer.total}** | **100%** | All non-verified rows are mapped to active completion issues (#218–#262). |`);
  }

  lines.push('');
  lines.push('---');
  lines.push('*Generated automatically by `scripts/gen_status.mjs`. Use `npm run docs:status` to regenerate.*');
  lines.push('');

  const output = lines.join('\n');
  fs.writeFileSync(statusPath, output, 'utf8');
  return { path: statusPath, sha256, modules: modules.length, reachableCount, orphanedCount };
}

if (process.argv[1] && path.resolve(process.argv[1]) === path.resolve(__filename)) {
  const res = generateStatusDoc();
  console.log(`✓ Generated ${res.path} from audit hash ${res.sha256.slice(0, 8)} (${res.reachableCount}/${res.modules} reachable)`);
}
