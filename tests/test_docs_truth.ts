/**
 * Documentation Truthfulness Test (Issue #220 - [TRU-02])
 *
 * Verifies that documentation, specifications, and README do not contain false,
 * misleading, or unproven claims from scripts/banned_claims.json unless the
 * release gate is completely green (PASSED).
 */

import * as assert from 'node:assert';
import { execSync } from 'node:child_process';
import * as fs from 'node:fs';
import * as path from 'node:path';

console.log('--- Testing Documentation Truth & Claims Hygiene (#220 - [TRU-02]) ---\n');

function testDocsTruth() {
  console.log('[#220 TRU-02] Verifying no banned or unverified claims in docs/README...');
  const bannedClaimsPath = path.resolve(process.cwd(), 'scripts/banned_claims.json');
  assert.strictEqual(fs.existsSync(bannedClaimsPath), true, 'scripts/banned_claims.json must exist');

  const bannedClaims: string[] = JSON.parse(fs.readFileSync(bannedClaimsPath, 'utf8'));

  // Run gate in memory with skip-unit and skip-e2e so unit runs do not nest the Electron e2e suite
  const jsonRaw = execSync('node scripts/release_gate.mjs --json --skip-unit --skip-e2e', {
    cwd: process.cwd(),
    encoding: 'utf8'
  });
  const gateReport = JSON.parse(jsonRaw);
  const isGateGreen = gateReport.status === 'PASSED';

  if (isGateGreen) {
    console.log('Release gate is PASSED: verified claims are permitted.');
    return;
  }

  console.log(`Gate is currently ${gateReport.status}. Enforcing strict ban on unverified claims...`);

  const filesToScan: string[] = [];

  // Add root files
  if (fs.existsSync(path.resolve(process.cwd(), 'README.md'))) {
    filesToScan.push(path.resolve(process.cwd(), 'README.md'));
  }
  if (fs.existsSync(path.resolve(process.cwd(), 'package.json'))) {
    filesToScan.push(path.resolve(process.cwd(), 'package.json'));
  }

  // Scan docs directory recursively (excluding release gate doc and attic)
  function scanDir(dir: string) {
    if (!fs.existsSync(dir)) return;
    const entries = fs.readdirSync(dir, { withFileTypes: true });
    for (const ent of entries) {
      const full = path.join(dir, ent.name);
      if (ent.isDirectory()) {
        if (ent.name !== 'attic' && ent.name !== 'node_modules') {
          scanDir(full);
        }
      } else if (ent.isFile() && ent.name.endsWith('.md')) {
        // Exclude release gate doc (which contains test output / check names)
        if (ent.name !== 'V1_RELEASE_GATE.md') {
          filesToScan.push(full);
        }
      }
    }
  }

  scanDir(path.resolve(process.cwd(), 'docs'));

  const violations: Array<{ file: string; line: number; phrase: string; snippet: string }> = [];

  for (const file of filesToScan) {
    const content = fs.readFileSync(file, 'utf8');
    const lines = content.split('\n');

    lines.forEach((lineText, idx) => {
      // Ignore markdown comments or historical mentions
      const trimmed = lineText.trim();
      if (trimmed.startsWith('<!--') || trimmed.startsWith('*Note:')) return;

      for (const phrase of bannedClaims) {
        if (lineText.toLowerCase().includes(phrase.toLowerCase())) {
          violations.push({
            file: path.relative(process.cwd(), file).replace(/\\/g, '/'),
            line: idx + 1,
            phrase,
            snippet: lineText.trim()
          });
        }
      }
    });
  }

  if (violations.length > 0) {
    console.error('Violations found:');
    for (const v of violations) {
      console.error(`  - ${v.file}:${v.line} matches "${v.phrase}": ${v.snippet}`);
    }
  }

  assert.strictEqual(
    violations.length,
    0,
    `Found ${violations.length} banned unverified claim(s) while release gate is NOT READY. See output above.`
  );

  console.log(`✓ All ${filesToScan.length} documents clean: zero banned unverified claims detected.\n`);
}

function testStatusDocHashCheck() {
  console.log('[#220 TRU-02] Verifying docs/STATUS.md generator consistency...');
  const statusPath = path.resolve(process.cwd(), 'docs/STATUS.md');
  assert.strictEqual(fs.existsSync(statusPath), true, 'docs/STATUS.md must exist');

  const firstLine = fs.readFileSync(statusPath, 'utf8').split('\n')[0];
  assert.ok(
    firstLine.startsWith('<!-- generated by scripts/gen_status.mjs from'),
    'docs/STATUS.md must start with generator hash header'
  );
  console.log('✓ docs/STATUS.md starts with valid generator header');
}

testDocsTruth();
testStatusDocHashCheck();

console.log('======================================================');
console.log('ALL DOCUMENTATION TRUTH TESTS PASSED (100%)');
console.log('======================================================');
